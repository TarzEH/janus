#!/usr/bin/env node
/**
 * Generates src/catalog/index.generated.ts from the technique files.
 *
 * Why generate instead of glob-import: import.meta.glob is Vite-only and
 * require.context is webpack-only, and this module has to load unchanged under
 * Next, tsup and Vitest. A checked-in generated barrel is the portable answer;
 * CI runs this with --check and fails on drift, exactly like a lockfile.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const techniquesDir = join(here, "..", "src", "catalog", "techniques");
const outFile = join(here, "..", "src", "catalog", "index.generated.ts");

const files = readdirSync(techniquesDir)
  .filter((f) => f.endsWith(".ts") && !f.endsWith(".test.ts"))
  .sort();

const entries = files.map((file) => {
  const m = /^(JNS-\d{4})-[a-z0-9-]+\.ts$/.exec(file);
  if (!m) {
    throw new Error(
      `Bad technique filename "${file}". Expected JNS-####-kebab-slug.ts — the id must be in the filename so PRs never collide.`,
    );
  }
  const id = m[1];
  const symbol = id.replace("-", "_");
  const src = readFileSync(join(techniquesDir, file), "utf8");
  if (!src.includes(`export const ${symbol}`)) {
    throw new Error(`${file} must export a const named ${symbol}.`);
  }
  return { file, symbol };
});

const body = `// GENERATED by scripts/gen-catalog-index.mjs — do not edit.
// Run \`npm run catalog:index\` after adding a technique.
import type { TechniqueInput } from "../schema/technique.js";
${entries.map((e) => `import { ${e.symbol} } from "./techniques/${e.file.replace(/\.ts$/, ".js")}";`).join("\n")}

export const RAW_TECHNIQUES: readonly TechniqueInput[] = [
${entries.map((e) => `  ${e.symbol},`).join("\n")}
];
`;

const check = process.argv.includes("--check");
let current = "";
try {
  current = readFileSync(outFile, "utf8");
} catch {
  /* first run */
}

if (check) {
  if (current !== body) {
    console.error(
      "catalog index is stale. Run `npm run catalog:index` and commit the result.",
    );
    process.exit(1);
  }
  console.log(`catalog index up to date (${entries.length} techniques)`);
} else {
  if (current !== body) writeFileSync(outFile, body);
  console.log(`catalog index: ${entries.length} techniques`);
}
